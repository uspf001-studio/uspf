export type HomepageContent = typeof homepageContentDefaults;

export type EditableHomepageValue =
  | string
  | EditableHomepageValue[]
  | { [key: string]: EditableHomepageValue };

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function normalizeValue(defaultValue: EditableHomepageValue, value: unknown): EditableHomepageValue {
  if (typeof defaultValue === "string") {
    return typeof value === "string" ? value : defaultValue;
  }

  if (Array.isArray(defaultValue)) {
    if (!Array.isArray(value)) return defaultValue;
    const template = defaultValue[0];
    if (template === undefined) return [];
    return value.map((item) => normalizeValue(template, item));
  }

  if (isRecord(defaultValue)) {
    const candidate = isRecord(value) ? value : {};
    return Object.fromEntries(
      Object.entries(defaultValue).map(([key, defaultEntry]) => [
        key,
        normalizeValue(defaultEntry, candidate[key]),
      ]),
    );
  }

  return defaultValue;
}

export function normalizeHomepageContent(value: unknown): HomepageContent {
  return normalizeValue(
    homepageContentDefaults as EditableHomepageValue,
    value,
  ) as HomepageContent;
}
